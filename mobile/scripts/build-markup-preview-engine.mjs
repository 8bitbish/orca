import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import * as esbuild from 'esbuild'

const mobileRoot = path.resolve(import.meta.dirname, '..')
const previewDir = path.join(mobileRoot, 'src', 'components', 'markup-preview')
const outputPath = path.join(previewDir, 'markup-preview-engine.generated.ts')

// Why a hash: the preview page's CSP admits exactly this script and nothing the agent wrote.
async function main() {
  const dompurify = JSON.parse(
    await readFile(path.join(mobileRoot, 'node_modules', 'dompurify', 'package.json'), 'utf8')
  )
  const result = await esbuild.build({
    entryPoints: [path.join(previewDir, 'markup-preview-engine.webview.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    minify: true,
    legalComments: 'none',
    target: 'chrome74'
  })
  // A literal </script> would close the inline tag; \/ means the same in JS.
  const js = result.outputFiles[0].text.trim().replace(/<\/script/gi, '<\\/script')
  const hash = createHash('sha256').update(js, 'utf8').digest('base64')
  const source = [
    '// Generated by scripts/build-markup-preview-engine.mjs from markup-preview-engine.webview.ts.',
    `// Bundles dompurify@${dompurify.version}. Do not edit by hand; regenerate via pnpm postinstall.`,
    `export const MARKUP_PREVIEW_ENGINE_JS = ${JSON.stringify(js)}`,
    `export const MARKUP_PREVIEW_ENGINE_HASH = ${JSON.stringify(`sha256-${hash}`)}`,
    ''
  ].join('\n')
  await writeFile(outputPath, source)
}

await main()
