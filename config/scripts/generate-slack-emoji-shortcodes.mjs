// Why generated: mobile's Metro bundle only sees src/shared, not the root node_modules where
// emojibase-data lives, so the Slack shortcode table has to be a source module both builds read.
// Run `pnpm run generate:slack-emoji-shortcodes` after bumping emojibase-data.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import process from 'node:process'

const REPO_ROOT = path.resolve(import.meta.dirname, '..', '..')
const OUTPUT_PATH = path.join(REPO_ROOT, 'src', 'shared', 'slack-emoji-shortcodes-data.ts')
const require = createRequire(import.meta.url)
const { version } = require('emojibase-data/package.json')
// iamcal/emoji-data short names are the ones Slack uses.
const iamcal = require('emojibase-data/en/shortcodes/iamcal.json')
const data = require('emojibase-data/en/data.json')

// Slack-only aliases that iamcal does not list.
const EXTRA_ALIASES = { simple_smile: '1F642' }
const TONES = [0x1f3fb, 0x1f3fc, 0x1f3fd, 0x1f3fe, 0x1f3ff]
const ENTRIES_PER_LINE = 40

const byHexcode = new Map(data.map((emoji) => [emoji.hexcode, emoji]))
const codepoints = (text) => Array.from(text, (char) => char.codePointAt(0))
const hex = (text) =>
  codepoints(text)
    .map((point) => point.toString(16))
    .join('-')

/**
 * The emoji as Slack draws it: emojibase appends FE0F to every emoji with a text variant,
 * but a single codepoint that already defaults to emoji presentation (type 1) needs none.
 */
function presentation(emoji) {
  const points = codepoints(emoji.emoji)
  return emoji.type === 1 && points.length === 2 && points[1] === 0xfe0f
    ? String.fromCodePoint(points[0])
    : emoji.emoji
}

/** Unicode's default placement: the modifier right after the base, dropping its FE0F. */
function derivedTone(unicode, tone) {
  const [base, ...rest] = codepoints(unicode)
  const tail = rest[0] === 0xfe0f ? rest.slice(1) : rest
  return String.fromCodePoint(base, tone, ...tail)
}

function uniformSkins(emoji) {
  const skins = emoji.skins ?? []
  const toned = TONES.map((tone) =>
    skins.find((skin) => {
      const modifiers = codepoints(skin.emoji).filter((point) => TONES.includes(point))
      return modifiers.length > 0 && modifiers.every((point) => point === tone)
    })
  )
  return toned.every(Boolean) ? toned.map((skin) => skin.emoji) : null
}

const names = new Map()
for (const [hexcode, value] of Object.entries(iamcal)) {
  for (const name of [].concat(value)) {
    names.set(name, hexcode)
  }
}
for (const [name, hexcode] of Object.entries(EXTRA_ALIASES)) {
  if (!names.has(name)) {
    names.set(name, hexcode)
  }
}

const grouped = new Map()
for (const [name, hexcode] of names) {
  if (!/^[a-z0-9_+-]+$/.test(name)) {
    throw new Error(`Unexpected shortcode charset: ${name}`)
  }
  const emoji = byHexcode.get(hexcode)
  if (!emoji) {
    throw new Error(`No emoji for ${name} (${hexcode})`)
  }
  const group = grouped.get(hexcode) ?? { emoji, names: [] }
  group.names.push(name)
  grouped.set(hexcode, group)
}

const entries = []
const exceptions = []
for (const { emoji, names: aliases } of grouped.values()) {
  const skins = uniformSkins(emoji)
  const unicode = presentation(emoji)
  entries.push(`${skins ? '~' : ''}${hex(unicode)}=${aliases.join(',')}`)
  if (skins && skins.some((skin, index) => skin !== derivedTone(unicode, TONES[index]))) {
    exceptions.push(`${aliases[0]}=${skins.map(hex).join('|')}`)
  }
}

const lines = (list) => {
  const out = []
  for (let index = 0; index < list.length; index += ENTRIES_PER_LINE) {
    out.push(`  '${list.slice(index, index + ENTRIES_PER_LINE).join(' ')}'`)
  }
  return out.join(',\n')
}

const source = `// GENERATED by config/scripts/generate-slack-emoji-shortcodes.mjs. Do not edit;
// run \`pnpm run generate:slack-emoji-shortcodes\`.
// Source: emojibase-data ${version} (MIT, Miles Johnson): en/shortcodes/iamcal.json, the
// iamcal/emoji-data short names Slack uses (MIT, Cal Henderson), joined to en/data.json.
// Entry: \`[~]<hex codepoints>=<name>[,<alias>…]\`; \`~\` marks skin-tone support.

export const SLACK_EMOJI_ENTRIES: readonly string[] = [
${lines(entries)}
]

/** Skin-toned forms (tones 2–6) where the modifier does not simply follow the first codepoint. */
export const SLACK_EMOJI_TONE_EXCEPTIONS: readonly string[] = [
${lines(exceptions)}
]
`

if (process.argv.includes('--check')) {
  if (readFileSync(OUTPUT_PATH, 'utf8') !== source) {
    console.error(`${path.relative(REPO_ROOT, OUTPUT_PATH)} is stale; regenerate it.`)
    process.exit(1)
  }
} else {
  writeFileSync(OUTPUT_PATH, source)
  console.log(
    `Wrote ${entries.length} emoji (${names.size} names, ${exceptions.length} tone exceptions).`
  )
}
